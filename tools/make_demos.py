def example3():
    d = Demo("example3", 3,
             dict(zh="例 3：Si VIII 2s²2p³ 和 2p⁵，rcsfinteract 与 M1 跃迁",
                  en="Example 3: Si VIII 2s²2p³ and 2p⁵, rcsfinteract and M1 transitions"),
             dict(zh="2s²2p³ 与 2p⁵ 的多参考 Dirac-Fock，到 n = 3 的单、双激发 (用 rcsfinteract 只保留与参考组态有"
                     "相互作用的 CSF)，MCDHF 和 CI，计算同一组能级之间的 M1 跃迁 (同一个计算，不需要双正交变换)。"
                     "手册中换到 LK、JK 耦合的部分没有收录。",
                  en="Multireference Dirac-Fock for 2s²2p³ and 2p⁵, single and double excitations to n = 3 (with "
                     "rcsfinteract keeping only the CSFs that interact with the reference), MCDHF and CI, and M1 "
                     "transitions between the levels of this one calculation (no biorthogonal transformation is "
                     "needed). The part of the manual on LK and JK coupling is not included."),
             dict(zh="约半分钟", en="about half a minute"),
             "example3/script", ["2s22p3_2p5_3.cm"])
    df, n3 = "2s22p3_2p5_DF", "2s22p3_2p5_3"
    levels = ["1-2", "1-4", "1"]
    d.nucleus("14", "28", "27.9769271")
    d.csfs([(["1s(2,i)2s(2,i)2p(3,i)", "1s(2,i)2p(5,i)"], "2s,2p", ("1", "5"), "0")], f"{df}.c",
           src="rcsfgenerate_input1")
    d.angular(f"{df}.c")
    d.estimate("3", src="rwfnestimate_input1")
    d.scf(levels, "*", df, spec="*", src="rmcdhf_input1")
    d.csfs([(["1s(2,*)2s(2,*)2p(3,*)", "1s(2,*)2p(5,*)"], "3s,3p,3d", ("1", "5"), "2")], f"{n3}.c",
           src="rcsfgenerate_input2")
    d.add("rcsfinteract", "rcsfinteract_input", mr=f"{df}.c", full=f"{n3}.c", ham="1", saveas=f"{n3}.c")
    d.angular(f"{n3}.c")
    d.estimate("3", f"{df}.w")
    d.scf(levels, "3*", n3, src="rmcdhf_input2")
    d.ci(n3, levels, nqed="3", src="rci_input")
    d.lsj(n3, src="jj2lsj_input")
    d.add("rlevels", files=f"{n3}.cm", log="energy3_LSJ")
    # both states come from the same calculation: the transformed files are copies
    d.cp(f"{n3}.w", f"{n3}.bw")
    d.cp(f"{n3}.cm", f"{n3}.cbm")
    d.add("rtransition", "rtransition_input", ci=True, init=n3, final=n3, kind="M1", m1_diffj=False,
          log="out_transition")
    return d


