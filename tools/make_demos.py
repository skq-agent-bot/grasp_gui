def stdin_of(job):
    step = STEPS[job["step"]]
    return step.stdin({f.key: core.normalize(f, job["vals"][f.key]) for f in step.fields
                       if isinstance(f, core.Field)})


def norm(text):
    return [ln.strip() for ln in text.strip().splitlines()]


def find(roots, d, name):
    for root in roots:
        path = os.path.join(root, d.src, name)
        if os.path.exists(path):
            return path
    return None


def check(d, roots):
    """Compare the generated input with the manual's input files; return the number of differences."""
    bad = 0
    for i, src in d.checks:
        if not src:
            continue
        with open(find(roots, d, src)) as f:
            want = f.read()
        got = stdin_of(d.jobs[i])
        if norm(got) != norm(want):
            bad += 1
            print(f"  {d.id} job {i + 1} ({d.jobs[i]['step']}) differs from {src}:\n"
                  f"    manual: {norm(want)}\n    demo:   {norm(got)}")
    return bad


def reference(d, roots):
    out = []
    for name in d.refs:
        path = find(roots, d, name)
        if not path:
            print(f"  {d.id}: no reference result {name}")
            continue
        blocks = grasp_mix.read_mix(path)
        out.append(dict(file=name, energies=[round(lv.energy, 10) for b in blocks for lv in b.levels]))
    return out


def main():
    roots = sys.argv[sys.argv.index("--check") + 1:] if "--check" in sys.argv else []
    os.makedirs(OUT, exist_ok=True)
    bad = 0
    for make in DEMOS:
        d = make()
        data = d.json()
        path = os.path.join(OUT, f"{d.id}.json")
        if roots:
            bad += check(d, roots)
            data["reference"] = reference(d, roots)
        elif os.path.exists(path):          # keep the reference energies of the existing file
            with open(path, encoding="utf-8") as f:
                data["reference"] = json.load(f).get("reference", [])
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
            f.write("\n")
        print(f"{path}: {len(d.jobs)} jobs")
    if bad:
        sys.exit(f"{bad} differences")


if __name__ == "__main__":
    main()
