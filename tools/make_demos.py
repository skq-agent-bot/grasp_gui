#!/usr/bin/env python3
"""Generate demos/*.json from the examples of the GRASP2018 manual and of GRASPG (graspgtest).

    tools/make_demos.py                       write demos/*.json
    tools/make_demos.py --check DIR...        also compare the generated program input with the manual's input
                                              files and take the reference energies from the results of the
                                              manual's scripts; each DIR is a copy of GRASP2018's grasptest
                                              (or GRASPG's graspgtest) directory, the first one that has a
                                              file is used

The demos are shared configurations (grasp_config.py, docs/CONFIG_FORMAT.md). Each job is given as the values of
the GUI form of that program, so that the imported demo shows them in the forms; the program input (stdin) is
generated by the GUI as for any other run.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import grasp_config          # noqa: E402
import grasp_core as core    # noqa: E402
import grasp_mix             # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "demos")
STEPS = {s.key: s for s in core.STEPS}


class Demo:
    def __init__(self, id, order, title, summary, runtime, src, refs):
        self.id, self.order, self.title, self.summary, self.runtime = id, order, title, summary, runtime
        self.src = src              # script directory in grasptest
        self.refs = refs            # result files whose energies are the reference
        self.jobs = []
        self.checks = []            # (job index, manual input file or None)
        self.group = None

    def add(self, step, src=None, **vals):
        fields = {f.key for f in STEPS[step].fields if isinstance(f, core.Field)}
        unknown = set(vals) - fields
        assert not unknown, f"{self.id}: {step} has no field {unknown}"
        full = dict(STEPS[step].defaults(), **vals)
        job = dict(step=step, vals=full)
        if step in core.GROUP_STEPS and self.group:
            job["group"] = self.group
        self.checks.append((len(self.jobs), src))
        self.jobs.append(job)

    # shortcuts for the common programs
    def nucleus(self, z, a, mass, spin="1", mu="1", q="1", src="rnucleus_input"):
        self.add("rnucleus", src, z=z, a=a, revise=False, mass=mass, spin=spin, mu=mu, q=q)

    def csfs(self, lists, saveas, core_="0", src=None):
        self.add("rcsfgenerate", src, order="*", core=core_, saveas=saveas,
                 lists=[dict(configs="\n".join(c), active=act, jmin=j[0], jmax=j[1], nexc=n)
                        for c, act, j, n in lists])

    def angular(self, csf, src="rangular_input"):
        self.add("rangular", src, csf=csf)

    def estimate(self, method="2", wfile="", delz="0", src=None):
        self.add("rwfnestimate", src, use_file=bool(wfile), wfile=wfile, forbs="*", method=method, orbs="*",
                 delz=delz)

    def scf(self, levels, vary, save, spec="", mem=False, nscf="100", log="", src=None):
        self.add("rmcdhf", src, mem=mem, levels="\n".join(levels), weights="5", uweights="", vary=vary, spec=spec,
                 nscf=nscf, log=log, save=save)

    def ci(self, state, levels, nqed="4", modfreq=True, copyfrom="", log="", src=None):
        self.add("rci", src, state=state, copyfrom=copyfrom, trans=True, modfreq=modfreq, factor="1.d-6", vp=True,
                 nms=False, sms=False, se=True, nqed=nqed, levels="\n".join(levels), log=log)

    def lsj(self, state, ci=True, log="", src=None):
        self.add("jj2lsj", src, state=state, ci=ci, unique=True, log=log)

    def custom(self, prog, args="", stdin="", log="", src=None):
        self.add("custom", src, prog=prog, args=args, stdin=stdin, log=log)

    def cp(self, src, dst):
        self.custom("cp", f"{src} {dst}")

    def json(self):
        package = core.package_of(j["step"] for j in self.jobs)
        return dict(format=grasp_config.FORMAT, version=grasp_config.VERSION, package=package, id=self.id,
                    order=self.order, title=self.title, summary=self.summary, runtime=self.runtime, jobs=self.jobs)


def example1():
    d = Demo("example1", 1,
             dict(zh="例 1：Li I 2s ²S 和 2p ²P", en="Example 1: Li I 2s ²S and 2p ²P"),
             dict(zh="入门示例。先做 2s 和 2p 的 Dirac-Hartree-Fock 计算，再分别加入到 n = 3 的单、双、三重激发做 "
                     "MCDHF，接着做含 Breit 和 QED 修正的 CI、变换到 LSJ 耦合，计算超精细常数、同位素移位、2s–2p 的 "
                     "E1 跃迁，最后生成能级表和跃迁表 (rtablevels、rtabtrans1/2)。",
                  en="A first example. Dirac-Hartree-Fock for 2s and 2p, then MCDHF with single, double and triple "
                     "excitations to n = 3 for each state, CI with Breit and QED corrections, transformation to LSJ "
                     "coupling, hyperfine constants, isotope shifts, the 2s–2p E1 transition, and energy and "
                     "transition tables (rtablevels, rtabtrans1/2)."),
             dict(zh="几秒钟", en="a few seconds"),
             "example1/script", ["2s_3.cm", "2p_3.cm"])
    d.nucleus("3", "7", "6.941", "1.5", "3.2564268", "-0.040")
    d.csfs([(["1s(2,i)2s(1,i)"], "2s,2p", ("1", "1"), "0"),
            (["1s(2,i)2p(1,i)"], "2s,2p", ("1", "3"), "0")], "2s_2p_DF.c", src="rcsfgenerate_input1")
    d.angular("2s_2p_DF.c")
    d.estimate("2", src="rwfnestimate_input1")
    d.scf(["1", "1", "1"], "*", "2s_2p_DF", spec="*", mem=True, src="rmcdhf_input1")
    for state, conf, j, levels in [("2s_3", "1s(2,*)2s(1,*)", ("1", "1"), ["1"]),
                                   ("2p_3", "1s(2,*)2p(1,*)", ("1", "3"), ["1", "1"])]:
        k = "2" if state == "2s_3" else "3"
        d.csfs([([conf], "3s,3p,3d", j, "3")], f"{state}.c", src=f"rcsfgenerate_input{k}")
        d.angular(f"{state}.c")
        d.estimate("2", "2s_2p_DF.w", src=None if k == "2" else "rwfnestimate_input3")
        d.scf(levels, "3*", state, mem=True, src=f"rmcdhf_input{k}")
        d.ci(state, levels, nqed="3", src=f"rci_input{k}")
        d.lsj(state, src=f"jj2lsj_input{k}")
    for state, s in [("2s_3", "2S"), ("2p_3", "2P")]:
        d.add("rhfs", f"rhfs_input{s}", state=state, ci=True, lsj=False)
    for state, s in [("2s_3", "2S"), ("2p_3", "2P")]:
        d.add("ris4", f"ris_input{s}", state=state, ci=True, higher=True, save=True)
    d.add("rbiotransform", "rbiotransform_input", ci=True, init="2s_3", final="2p_3", log="out_rbiotransform")
    d.add("rtransition", "rtransition_input", ci=True, init="2s_3", final="2p_3", kind="E1", log="out_transition")
    d.add("rlevels", files="2s_3.cm 2p_3.cm", log="energy3")
    d.add("rtablevels", "rtablevels_input", nskip="0", files="energy3")
    d.add("rtabtrans1", "rtabtrans1_inp", files="2s_3.cm\n2p_3.cm", nskip="0", fmt="0")
    d.add("rtabtrans2", "rtabtrans2_inp", tfile="2s_3.2p_3.ct", fmt="0", cutoff="0", frac="0", sorted=True,
          digits="3")
    return d


